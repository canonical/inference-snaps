// Command docgen generates the CLI reference documentation from the command tree
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/canonical/inference-snaps/modelctl/v2/commands"
	"github.com/canonical/inference-snaps/modelctl/v2/commands/common"
	"github.com/canonical/inference-snaps/modelctl/v2/internal/storage"
	"github.com/spf13/cobra"
)

const rootName = "<inference-snap>"

func main() {
	out := flag.String("out", "../docs/reuse/cli-commands.txt", "output file")
	flag.Parse()

	ctx := &common.Context{
		Cache:  storage.NewMockCache(),
		Config: storage.NewMockConfig(),
	}
	// Enable all optional commands so they are documented
	root, err := commands.NewRootCmd(ctx, commands.RootOptions{Name: rootName, Chat: true, WebUi: true})
	if err != nil {
		log.Fatalf("Error building command tree: %v", err)
	}

	var buf bytes.Buffer
	writePage(&buf, root)

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		log.Fatalf("Error creating output directory: %v", err)
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
		log.Fatalf("Error writing docs: %v", err)
	}
}

func writePage(buf *bytes.Buffer, root *cobra.Command) {
	buf.WriteString("<!-- Code generated by modelctl/internal/tools/docgen. DO NOT EDIT. Regenerate with: make -C modelctl docs-cli -->\n")

	if flags := root.PersistentFlags().FlagUsages(); flags != "" {
		fmt.Fprintf(buf, "\n## Global options\n\n%s", codeBlock("text", flags))
	}

	for _, g := range root.Groups() {
		// Reuse the help text group titles, e.g. "Basic Commands:" -> "Basic commands"
		writeSection(buf, root, g.ID, sentenceCase(strings.TrimSuffix(g.Title, ":")))
	}
	// Commands without a group are listed as "Additional Commands" in the help text
	writeSection(buf, root, "", "Additional commands")
}

func writeSection(buf *bytes.Buffer, root *cobra.Command, groupID, title string) {
	var cmds []*cobra.Command
	for _, cmd := range root.Commands() {
		if cmd.GroupID == groupID && cmd.IsAvailableCommand() {
			cmds = append(cmds, cmd)
		}
	}
	if len(cmds) == 0 {
		return
	}

	fmt.Fprintf(buf, "\n## %s\n", title)
	for _, cmd := range cmds {
		writeCommand(buf, root, cmd)
	}
}

// writeCommand renders cmd and its subcommands, skipping hidden and deprecated ones
func writeCommand(buf *bytes.Buffer, root, cmd *cobra.Command) {
	// Drop the root name from the path, e.g. "<inference-snap> use-engine" -> "use-engine"
	name := strings.TrimPrefix(cmd.CommandPath(), root.Name()+" ")
	description := cmd.Long
	if description == "" {
		description = cmd.Short
	}
	// Append the arguments from Use to the full path, e.g. Use "get [<key>]" -> "<inference-snap> get [<key>]"
	usage := cmd.CommandPath()
	if _, args, found := strings.Cut(cmd.Use, " "); found {
		usage += " " + args
	}

	// The MyST target lets other pages reference the command with {ref}, e.g. "use-engine" -> "(cli-use-engine)="
	fmt.Fprintf(buf, "\n(cli-%s)=\n\n", strings.ReplaceAll(name, " ", "-"))
	fmt.Fprintf(buf, "### `%s`\n\n", name)
	fmt.Fprintf(buf, "%s\n\n", escapeMarkdown(description))
	buf.WriteString(codeBlock("shell", usage))

	// Hidden flags are omitted, and so is help since every command has it
	if flags := cmd.LocalFlags().FlagUsages(); flags != "" {
		fmt.Fprintf(buf, "\n%s", codeBlock("text", flags))
	}
	if cmd.Example != "" {
		fmt.Fprintf(buf, "\nExamples:\n\n%s", codeBlock("shell", cmd.Example))
	}

	for _, sub := range cmd.Commands() {
		if sub.IsAvailableCommand() {
			writeCommand(buf, root, sub)
		}
	}
}

// codeBlock renders text as a fenced code block, e.g. ("shell", "ls") -> "```shell\nls\n```\n"
// A trailing newline in text is dropped, since flag usages end with one but examples don't
func codeBlock(lang, text string) string {
	return "```" + lang + "\n" + strings.TrimSuffix(text, "\n") + "\n```\n"
}

// escapeMarkdown escapes help text that would otherwise be parsed as HTML, such as <key>
func escapeMarkdown(text string) string {
	return strings.ReplaceAll(text, "<", `\<`)
}

// sentenceCase converts a title such as "Basic Commands" to "Basic commands"
func sentenceCase(title string) string {
	if title == "" {
		return title
	}
	return title[:1] + strings.ToLower(title[1:])
}
